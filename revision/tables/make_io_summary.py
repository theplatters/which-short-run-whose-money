#!/usr/bin/env python3
from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TABLE = ROOT / "data" / "I-O_DE2019_formatiert.csv"
OUT = ROOT / "revision" / "tables" / "tableA6_io-summary.tex"


def _num(cell: str) -> float:
    s = cell.strip()
    return 0.0 if s in {"-", "", "x"} else float(s)


def read_table():
    rows = list(csv.reader(open(TABLE, encoding="utf-8-sig"), delimiter=";", quotechar='"'))
    header, body = rows[0][1:], rows[1:]
    labels = [r[0].strip() for r in body]
    M = [[_num(c) for c in r[1:]] for r in body]

    def row(prefix: str) -> int:
        hits = [k for k, l in enumerate(labels) if l.startswith(prefix)]
        if not hits:
            raise KeyError(f"row {prefix!r} not found")
        return hits[0]

    def col(name: str) -> int:
        hits = [k for k, h in enumerate(header) if name.lower() in h.strip().lower()]
        if not hits:
            raise KeyError(f"column {name!r} not found in {header}")
        return hits[0]

    return header, labels, M, row, col


def compute(diagnose: bool = False):
    header, labels, M, row, col = read_table()
    if diagnose:
        print(f"{len(header)} columns, {len(labels)} rows")
        for k, h in enumerate(header):
            print(f"  col {k:3d}: {h.strip()}")

    SECT = 71                      # the 71 using sectors are columns 0..70
    OWN = 71                       # household own-use (row 72 of the product block)
    PROD = 72                      # the 72 product rows, own-use included
    def rsum(name: str, lo: int, hi: int) -> float:
        return sum(M[row(name)][lo:hi])

    gross = rsum("Produktionswert", 0, SECT)
    dom_int = sum(sum(M[k][0:SECT]) for k in range(SECT))
    imp_int = rsum("Verwendung der Importe", 0, SECT)
    tax_int = rsum("Gütersteuern abzüglich Gütersubventionen", 0, SECT)
    gva = rsum("Bruttowertschöpfung", 0, SECT)
    own_use = M[row("Produktionswert")][OWN]
    own_use_row = sum(M[row("Waren u.Dienstleistungen privater Haushalte")][c]
                      for c in range(73, 80))
    assert abs(own_use - own_use_row) < 1e-6, (own_use, own_use_row)

    if diagnose:
        print("gross", gross, "dom_int", dom_int, "imp_int", imp_int,
              "tax_int", tax_int, "gva", gva, "own_use", own_use)

    # the seven final-use columns, by name (recipe: private households, NPOS,
    # government, equipment, buildings, inventories, total exports)
    fd_names = ("Konsumausgaben der privaten Haushalte im Inland",
                "Konsumausgaben der privaten Organisationen o.E.",
                "Konsumausgaben des Staates",
                "Anlageinvestitionen f.Ausrüstungen u.sonst.Anlagen",
                "Anlageinvestitionen für Bauten",
                "Vorratsveränderungen und Nettozugang an Wertsachen",
                "Exporte")
    fd_cols = [col(s) for s in fd_names]
    if diagnose:
        print("final-use columns:", [(c, header[c].strip()) for c in fd_cols])

    def csum(name: str) -> float:
        return sum(M[row(name)][c] for c in fd_cols)

    dom_fd = sum(sum(M[k][c] for c in fd_cols) for k in range(PROD))
    imp_fd = csum("Verwendung der Importe")
    tax_fd = csum("Gütersteuern abzüglich Gütersubventionen")
    fd_total = dom_fd + imp_fd + tax_fd
    # modeled-sector GDP excludes the own-use row, which the lower block includes
    gdp_exp = dom_fd - own_use - imp_int - tax_int

    if diagnose:
        print("dom_fd", dom_fd, "imp_fd", imp_fd, "tax_fd", tax_fd,
              "fd_total", fd_total, "gdp_exp", gdp_exp)

    # canaries: the identities the caption claims
    assert abs(gross - (dom_int + imp_int + tax_int + gva)) < 1e-6, "gross output identity"
    assert abs(fd_total - (dom_fd + imp_fd + tax_fd)) < 1e-6, "final demand identity"
    assert abs(gdp_exp - gva) < 1e-6, "expenditure GDP = production GDP"
    return dict(gross=gross, dom_int=dom_int, imp_int=imp_int, tax_int=tax_int,
                gva=gva, fd_total=fd_total, dom_fd=dom_fd, imp_fd=imp_fd,
                tax_fd=tax_fd, gdp=gva, residual=gdp_exp - gva, own_use=own_use)


def eur(x: float) -> str:
    return f"{round(x):,}".replace(",", "{,}")


def pct(part: float, whole: float) -> str:
    return f"{part / whole * 100:.1f}"


def build(d: dict) -> str:
    g, fd, gdp = d["gross"], d["fd_total"], d["gdp"]
    return f"""% =====================================================================
% Table --- the German 2019 input--output account in summary (Sec. 4.1)
% ---------------------------------------------------------------------
% GENERATED by revision/tables/make_io_summary.py -- do not edit numbers by
% hand. Regenerate with: python3 revision/tables/make_io_summary.py
% Requested by reviewer 1 (R1.3: \"key economic variables from Germany's IO
% table in a summary table\"). Every number is computed from
% data/I-O_DE2019_formatiert.csv by LABEL lookup (never by position):
%   gross output            row \"Produktionswert\" over the 71 using sectors
%   domestic intermediate use   rows 1-71 over the same columns
%   imported intermediates  row \"Verwendung der Importe\"
%   product taxes           row \"Gütersteuern abzüglich Gütersubventionen\"
%   gross value added       row \"Bruttowertschöpfung\"
%   final demand            rows over the seven final-use columns
%                           (private households, NPOS, government,
%                           equipment, buildings, inventories, total exports)
%   expenditure GDP        final use over rows 1-71, less intermediate imports
%                           and product taxes on intermediate use, columns 2-72
%                           (excludes household own-use in row 72)
% Shares are of gross output (upper block) and of final demand at
% purchasers' prices (lower block). The pipeline and the consistency checks
% are documented in Appendix C; the Domar weights sum to 2.11.
% =====================================================================
\\begin{{table}}[t]
\\centering
\\small
\\begin{{tabular}}{{lrr}}
\\toprule
 & EUR m & percent \\\\
\\midrule
Gross output (basic prices) & ${eur(g)}$ & $100.0$ \\\\
\\quad domestic intermediate use & ${eur(d['dom_int'])}$ & ${pct(d['dom_int'], g)}$ \\\\
\\quad imported intermediates & ${eur(d['imp_int'])}$ & ${pct(d['imp_int'], g)}$ \\\\
\\quad product taxes on intermediate use & ${eur(d['tax_int'])}$ & ${pct(d['tax_int'], g)}$ \\\\
\\quad gross value added & ${eur(d['gva'])}$ & ${pct(d['gva'], g)}$ \\\\
\\addlinespace
Final demand at purchasers' prices & ${eur(fd)}$ & $100.0$ \\\\
\\quad domestic final demand & ${eur(d['dom_fd'])}$ & ${pct(d['dom_fd'], fd)}$ \\\\
\\quad imported final use & ${eur(d['imp_fd'])}$ & ${pct(d['imp_fd'], fd)}$ \\\\
\\quad product taxes on final use & ${eur(d['tax_fd'])}$ & ${pct(d['tax_fd'], fd)}$ \\\\
\\addlinespace
GDP, production side & ${eur(gdp)}$ &  \\\\
GDP, income side & ${eur(gdp)}$ &  \\\\
GDP, expenditure side (modeled sectors) & ${eur(d['gdp'] + d['residual'])}$ &  \\\\
residual, percent of GDP & ${eur(d['residual'])}$ & ${d['residual'] / gdp * 100:.3f}$ \\\\
\\bottomrule
\\end{{tabular}}
\\caption{{The German input--output account for 2019 in summary, with shares of
gross output in the upper block and of final demand at purchasers' prices in the
lower block. Production, income and expenditure agree exactly for the 71 modeled
sectors. Domestic final demand in the lower block includes ${eur(d['own_use'])}$~EUR~m of
household own-use in row 72, excluded from modeled-sector GDP. The expenditure
measure deducts imported intermediates and product taxes on intermediate use
from the modeled sectors' domestic final deliveries (Appendix~\\ref{{app:pipeline-checks}}).}}
\\label{{tab:io-summary}}
\\end{{table}}
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--diagnose", action="store_true")
    args = ap.parse_args()
    d = compute(args.diagnose)
    text = build(d)
    if args.check:
        cur = OUT.read_text()
        print("identical" if cur == text else "DIFFERS")
        return 0 if cur == text else 1
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
